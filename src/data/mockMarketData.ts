// Helper to generate realistic candles
function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.012) {
  const candles = [];
  let currentClose = basePrice * (1 - volatility * (count / 3));
  const now = new Date('2026-10-06T15:30:00Z');

  for (let i = count; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000).toLocaleTimeString([], {
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    });
    const change = (Math.random() - 0.47) * (basePrice * volatility);
    const open = currentClose;
    const close = Math.max(open * 0.8, open + change);
    const high = Math.max(open, close) + Math.random() * (basePrice * volatility * 0.6);
    const low = Math.min(open, close) - Math.random() * (basePrice * volatility * 0.6);
    const volume = Math.floor(15000 + Math.random() * 85000);

    candles.push({
      time,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentClose = close;
  }
  return candles;
}

